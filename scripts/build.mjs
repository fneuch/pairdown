import { build } from 'esbuild'
import { statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { ALLOWED_EXTERNALS } from './externals.mjs'

const root = fileURLToPath(new URL('..', import.meta.url))
const outfile = `${root}desktop/plugin.js`

await build({
  absWorkingDir: root,
  entryPoints: ['desktop/src/index.jsx'],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: ALLOWED_EXTERNALS,
  minify: false,
  legalComments: 'eof',
  banner: { js: '/* PairDown desktop plugin. Generated by scripts/build.mjs; do not edit. */' },
  logLevel: 'info'
})

console.log(`built desktop/plugin.js: ${statSync(outfile).size} bytes`)
